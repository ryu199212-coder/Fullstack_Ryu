// 재료명에서 키워드를 추출하는 함수 (예: "밥 2공기" -> "밥")
export function extractIngredientKeyword(ingredientStr: string): string {
  // 숫자, 단위, 특수문자 등을 제거하고 순수 재료명만 추출
  const cleanedStr = ingredientStr
    .replace(/[0-9]+/g, '') // 숫자 제거
    .replace(/[g|kg|ml|L|개|컵|큰술|작은술|쪽|톨|대|장|분|약간|적당량|적당히]/g, '') // 단위 제거
    .replace(/[\(\)]/g, '') // 괄호 제거
    .trim();
  
  // 여러 재료명 중 첫 번째 것만 사용
  const words = cleanedStr.split(/[,\/\s]+/);
  return words[0] || ingredientStr;
}

